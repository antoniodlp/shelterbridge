// Writes the countries reference data migration from ISO 3166-1 alpha-2 codes.
// Labels come from the ICU data bundled with Node (Intl.DisplayNames).
// Usage: node supabase/scripts/generate-countries-migration.mjs
import { writeFileSync } from 'node:fs'

const CODES = `
AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ
BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM
DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS
GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN
KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ
MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM
PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV
SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI
VN VU WF WS YE YT ZA ZM ZW
`.trim().split(/\s+/)

// Common countries of origin at FM4, listed first in pickers. FM4 to confirm (spec section 15).
const PRIORITY = ['MX', 'HN', 'GT', 'SV', 'NI', 'VE', 'CU', 'HT', 'CO', 'EC']

if (CODES.length !== 249 || new Set(CODES).size !== 249) {
  throw new Error(`Expected 249 unique codes, got ${CODES.length}`)
}

const es = new Intl.DisplayNames(['es-MX'], { type: 'region' })
const en = new Intl.DisplayNames(['en'], { type: 'region' })
const quote = (text) => `'${text.replaceAll("'", "''")}'`

const rows = CODES.map((code) => {
  const labels = JSON.stringify({ es: es.of(code), en: en.of(code) })
  const index = PRIORITY.indexOf(code)
  const sortOrder = index === -1 ? 1000 : index + 1
  return `  (${quote(code)}, ${quote(labels)}::jsonb, ${sortOrder})`
})

const sql = [
  '-- Generated by supabase/scripts/generate-countries-migration.mjs. Do not edit by hand.',
  'insert into public.countries (code, labels, sort_order) values',
  rows.join(',\n'),
  'on conflict (code) do nothing;',
  '',
].join('\n')

writeFileSync(new URL('../migrations/20261007000310_countries_data.sql', import.meta.url), sql)
console.log(`Wrote ${CODES.length} countries`)
